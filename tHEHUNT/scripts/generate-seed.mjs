#!/usr/bin/env node
// Writes supabase/seed/the_game_seed.sql from the game's own data files:
//   game/data/cases.ts    case titles, level titles, briefings, scores, coin rewards
//   game/data/secrets.ts  answers, Powerful Hints, the phone code (→ case fragments)
//   game/data/market.ts   the power-up catalogue (prices, limits, availability)
// Run it after editing those files:  npm run seed   — then run the SQL in Supabase.
// Safe to run repeatedly: it updates the "THE GAME" event in place and keeps progress.
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const load = (p) => import(pathToFileURL(resolve(root, p)).href);
const { CASES, LEVEL_SCORE, CASE_FRAGMENT_LENGTH } = await load('game/data/cases.ts');
const { ANSWERS, HINTS, UNLOCK_CODE } = await load('game/data/secrets.ts');
const { CATALOG, BLACK_MARKET_DISCOUNT, STARTING_COINS } = await load('game/data/market.ts');

const q = (s) => (s == null ? 'NULL' : `'${String(s).replace(/'/g, "''")}'`);
const problems = [];

// fragments: the phone code split in case order
const fragments = {};
let at = 0;
for (const c of CASES) {
  const n = CASE_FRAGMENT_LENGTH[c.id] ?? 0;
  fragments[c.id] = UNLOCK_CODE.slice(at, at + n);
  at += n;
}
if (at !== UNLOCK_CODE.length) problems.push(`case fragments add up to ${at} digits but UNLOCK_CODE has ${UNLOCK_CODE.length}`);
if (!/^\d+$/.test(UNLOCK_CODE)) problems.push('UNLOCK_CODE must be digits only');

const levels = [];
for (const c of CASES) {
  for (const l of c.levels) {
    const key = `${c.id}-${l.number}`;
    if (!ANSWERS[key]) problems.push(`no answer for case ${c.id} level ${l.number} (ANSWERS['${key}'])`);
    levels.push({ c, l, answer: ANSWERS[key] ?? '', hint: HINTS[key] ?? null, points: l.score ?? LEVEL_SCORE[l.number] ?? 0 });
  }
}
if (problems.length) {
  console.error('Cannot write the seed:\n  - ' + problems.join('\n  - '));
  process.exit(1);
}

const out = [];
out.push(`-- GENERATED by scripts/generate-seed.mjs — do not edit by hand.
-- Source: game/data/cases.ts, game/data/secrets.ts, game/data/market.ts
-- Contains the ANSWERS: keep this file private (it is git-ignored).
BEGIN;

DO $$
DECLARE v_event UUID; v_challenge UUID;
BEGIN
  SELECT id INTO v_event FROM events WHERE name = 'THE GAME' ORDER BY created_at DESC LIMIT 1;
  IF v_event IS NULL THEN
    INSERT INTO events (name, description, status, starting_coins, market_open, settings)
    VALUES ('THE GAME', 'Six case files, two markets and a locked phone.', 'live', ${Number(STARTING_COINS)}, true, '{"black_market_active": false}')
    RETURNING id INTO v_event;
  ELSE
    UPDATE events SET starting_coins = ${Number(STARTING_COINS)} WHERE id = v_event;
  END IF;
`);
for (const c of CASES) {
  out.push(`
  -- Case ${c.id}: ${c.title.replace(/\n/g, ' ')}
  SELECT id INTO v_challenge FROM challenges WHERE event_id = v_event AND display_order = ${c.id};
  IF v_challenge IS NULL THEN
    INSERT INTO challenges (event_id, title, display_order, status, final_fragment, fragment_order, category)
    VALUES (v_event, ${q(c.title)}, ${c.id}, 'published', ${q(fragments[c.id])}, ${c.id}, 'case') RETURNING id INTO v_challenge;
  ELSE
    UPDATE challenges SET title = ${q(c.title)}, status = 'published', final_fragment = ${q(fragments[c.id])}, fragment_order = ${c.id} WHERE id = v_challenge;
  END IF;`);
  for (const { l, answer, hint, points } of levels.filter((x) => x.c === c)) {
    out.push(`  INSERT INTO challenge_levels (challenge_id, level_number, title, prompt, answer, answer_mode, hint_text, points_reward, coins_reward, status)
  VALUES (v_challenge, ${l.number}, ${q(l.title)}, ${q(l.briefing)}, ${q(answer)}, 'game', ${q(hint)}, ${points}, ${l.reward}, 'published')
  ON CONFLICT (challenge_id, level_number) DO UPDATE SET title = EXCLUDED.title, prompt = EXCLUDED.prompt, answer = EXCLUDED.answer,
    answer_mode = 'game', hint_text = EXCLUDED.hint_text, points_reward = EXCLUDED.points_reward, coins_reward = EXCLUDED.coins_reward, status = 'published';`);
  }
}
out.push(`END $$;

-- Power-up catalogue (prices are enforced by the server; edit game/data/market.ts and re-run)`);
CATALOG.forEach((i, n) => {
  const black = i.blackPrice ?? Math.floor(i.normalPrice * (1 - BLACK_MARKET_DISCOUNT));
  const contains = `ARRAY[${(i.contains ?? []).map(q).join(', ')}]::text[]`;
  out.push(`INSERT INTO game_catalog (id, name, normal_price, black_price, available_normal, available_black, limit_normal, limit_black, contains, sort)
VALUES (${q(i.id)}, ${q(i.name)}, ${i.normalPrice}, ${black}, ${i.availability.normal}, ${i.availability.black}, ${i.limit.normal}, ${i.limit.black}, ${contains}, ${n})
ON CONFLICT (id) DO UPDATE SET name = EXCLUDED.name, normal_price = EXCLUDED.normal_price, black_price = EXCLUDED.black_price,
  available_normal = EXCLUDED.available_normal, available_black = EXCLUDED.available_black, limit_normal = EXCLUDED.limit_normal,
  limit_black = EXCLUDED.limit_black, contains = EXCLUDED.contains, sort = EXCLUDED.sort;`);
});
out.push('\nCOMMIT;\n');

const file = resolve(root, 'supabase/seed/the_game_seed.sql');
mkdirSync(dirname(file), { recursive: true });
writeFileSync(file, out.join('\n'));
console.log(`Wrote ${file}: ${CASES.length} cases, ${levels.length} levels, ${CATALOG.length} power-ups, code ${UNLOCK_CODE.length} digits.`);
